#!/usr/bin/env python3
"""Pre-render trusted repository components; runtime has no build dependency."""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parent.parent
COMPONENT = re.compile(r'<div data-component="([^"]+)"></div>')


def render(source, root=ROOT, stack=()):
    def expand(match):
        relative = match.group(1)
        path = (root / relative).resolve()
        if not path.is_relative_to((root / 'components').resolve()):
            raise ValueError(f'Component outside components/: {relative}')
        if path in stack:
            raise ValueError(f'Cyclic component: {relative}')
        content = render(path.read_text(encoding='utf-8'), root, (*stack, path))
        return f'<div data-component="{relative}">\n{content}</div>'
    return COMPONENT.sub(expand, source)


def bundle(root=ROOT):
    app = (root / 'assets/js/app.js').read_text(encoding='utf-8')
    translations = (root / 'assets/js/i18n.js').read_text(encoding='utf-8')
    dependency = "import { translations } from './i18n.js';"
    if app.count(dependency) != 1:
        raise ValueError('Expected one translations import; update the builder for changed module dependencies')
    return '// Generated by tools/build.py; edit app.js and i18n.js instead.\n' + app.replace(dependency, translations, 1)


def build(root=ROOT):
    html = render((root / 'templates/index.html').read_text(encoding='utf-8'), root)
    css_hash = hashlib.sha256((root / 'assets/css/styles.css').read_bytes()).hexdigest()[:16]
    js_hash = hashlib.sha256(bundle(root).encode('utf-8')).hexdigest()[:16]
    return html.replace('assets/css/styles.css"', f'assets/css/styles.css?v={css_hash}"').replace('assets/js/app.js"', f'assets/js/site.js?v={js_hash}"')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed HTML is stale')
    args = parser.parse_args()
    outputs = {ROOT / 'index.html': build(), ROOT / 'assets/js/site.js': bundle()}
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in outputs.items()
                 if not path.exists() or path.read_text(encoding='utf-8') != content]
        if stale:
            parser.exit(1, f'Stale generated files: {", ".join(stale)}. Run python3 tools/build.py\n')
        print('Generated HTML and runtime are current.')
    else:
        for path, content in outputs.items():
            path.write_text(content, encoding='utf-8')
        print('Rendered index.html and bundled assets/js/site.js.')


if __name__ == '__main__':
    main()
